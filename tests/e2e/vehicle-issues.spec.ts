import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('maxey-role', 'manager')
    localStorage.setItem('maxey-home-store', 'Howell')
  })
})

test('reports, assigns, and manager-confirms a vehicle issue through the real demo HTTP routes', async ({ page }, testInfo) => {
  const vin = testInfo.project.name === 'mobile' ? 'TESTDATAHWELL0002' : 'TESTDATAHWELL0001'
  await page.goto(`/inventory?scope=group&vin=${vin}`)

  const workspace = page.getByRole('dialog', { name: /vehicle workspace/ })
  await expect(workspace).toBeVisible({ timeout: 15_000 })
  await workspace.getByRole('button', { name: 'Report issue', exact: true }).click()

  const report = page.getByRole('dialog', { name: 'Report a vehicle issue' })
  await expect(report).toBeVisible()
  await report.getByLabel('Category').selectOption('cleaning')
  await report.getByLabel('Priority').selectOption('urgent')
  await report.getByLabel('What needs attention?').fill('Synthetic lot check found mud on the driver door.')
  await report.getByLabel(/Photos/).setInputFiles('public/demo-vehicles/f150.jpg')
  await expect(report.getByAltText('Selected issue photo 1')).toBeVisible()
  await report.getByRole('button', { name: 'Report issue', exact: true }).click()

  await expect(report).toBeHidden()
  await expect(workspace.getByRole('tab', { name: 'Issues' })).toHaveAttribute('aria-selected', 'true')
  const detail = workspace.getByRole('region', { name: 'Vehicle issue details' })
  await expect(detail.getByText('Cleaning issue')).toBeVisible()
  await expect(detail.getByText('Photos (1)', { exact: true })).toBeVisible()

  await detail.getByLabel('Action').selectOption('assign')
  await detail.getByLabel('Assign to').fill('Synthetic detail team')
  await detail.getByRole('button', { name: 'Assign', exact: true }).click()
  await expect(detail.getByText('Issue updated.')).toBeVisible()
  await expect(detail).toContainText('Synthetic detail team')

  await detail.getByLabel('Action').selectOption('complete')
  await detail.getByLabel('Completion note').fill('Synthetic manager inspected the cleaned door in person.')
  await detail.getByRole('button', { name: 'Confirm completion', exact: true }).click()
  await expect(detail.getByText('Completion confirmed.')).toBeVisible()
  await expect(detail.getByText('Completed', { exact: true })).toBeVisible()
})

test('keeps Vehicle issues at the top of Action center and manages reports with vehicle context and completion history', async ({ page }, testInfo) => {
  await page.goto('/attention?category=issues')
  await expect(page.getByRole('button', { name: /^Vehicle issues \d+$/ })).toHaveAttribute('aria-pressed', 'true')
  const ledger = page.getByRole('region', { name: 'Vehicle issue log' })
  await expect(ledger).toBeVisible()
  await ledger.getByRole('button', { name: 'Report issue', exact: true }).click()
  const report = page.getByRole('dialog', { name: 'Report a vehicle issue' })
  const stock = testInfo.project.name === 'mobile' ? 'DEMO-H02' : 'DEMO-H01'
  await report.getByLabel('Find the vehicle').fill(stock)
  await report.getByRole('button', { name: new RegExp(`Stock ${stock}`) }).click()
  await report.getByLabel('Category').selectOption('fuel')
  await report.getByLabel('What needs attention?').fill(`Synthetic issue ledger ${testInfo.project.name}: add fuel before the lot demonstration.`)
  await report.getByRole('button', { name: 'Report issue', exact: true }).click()
  await expect(report).toBeHidden()
  const detail = page.getByRole('dialog', { name: 'Vehicle issue', exact: true })
  await expect(detail.getByText('Fuel issue', { exact: true })).toBeVisible()
  await detail.getByLabel('Action').selectOption('request_completion')
  await detail.getByLabel('Work update').fill('Synthetic fuel added; manager review requested.')
  await detail.getByRole('button', { name: 'Send for manager review', exact: true }).click()
  await expect(detail.getByText('Sent for manager review.')).toBeVisible()
  await detail.getByRole('button', { name: 'Close vehicle issue' }).click()
  await ledger.getByRole('button', { name: /^Review \d+$/ }).click()
  const row = ledger.getByRole('listitem').filter({ hasText: `Synthetic issue ledger ${testInfo.project.name}:` })
  await expect(row).toContainText(stock)
  await expect(row).toContainText('Awaiting manager review')
  const review = row.getByRole('link', { name: /^Review work:/ })
  await review.click()
  await expect(detail.getByLabel('Action')).toHaveValue('complete')
  await expect(detail.getByRole('button', { name: 'Confirm completion' })).toBeDisabled()
  await detail.getByLabel('Completion note').fill('Synthetic manager verified the fuel gauge on the lot.')
  await detail.getByRole('button', { name: 'Confirm completion' }).click()
  await expect(detail.getByText('Completion confirmed.')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(detail).toBeHidden()
  await ledger.getByRole('button', { name: /^Completed \d+$/ }).click()
  const completed = ledger.getByRole('listitem').filter({ hasText: `Synthetic issue ledger ${testInfo.project.name}:` })
  await expect(completed).toContainText('Confirmed by Demo user')
  await completed.getByRole('link', { name: /^Reopen issue:/ }).click()
  await expect(detail.getByLabel('Action')).toHaveValue('reopen')
  await expect(detail.getByText('Completed', { exact: true })).toBeVisible()
  await detail.getByLabel('Work update').fill('Synthetic manager found another fuel check is needed.')
  await detail.getByRole('button', { name: 'Reopen issue', exact: true }).click()
  await expect(detail.getByText('Issue updated.')).toBeVisible()
  await expect(detail.getByText('Open', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(detail).toBeHidden()
  await ledger.getByRole('button', { name: /^Open \d+$/ }).click()
  await expect(ledger.getByRole('listitem').filter({ hasText: `Synthetic issue ledger ${testInfo.project.name}:` })).toContainText('Open')
  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await page.getByRole('region', { name: 'Work queue' }).getByRole('button', { name: /^Vehicle issues \d+$/ }).click()
  await expect(page.getByRole('link', { name: 'Vehicle issue log' })).toBeVisible()
  await page.getByRole('link', { name: 'Vehicle issue log' }).click()
  await expect(page.getByRole('button', { name: /^Vehicle issues \d+$/ })).toHaveAttribute('aria-pressed', 'true')
})
