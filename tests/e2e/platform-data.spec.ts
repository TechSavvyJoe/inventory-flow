import { expect, test } from '@playwright/test'

// The dedicated e2e server uses only in-memory synthetic owner/source records.
test('configures a dealership daily feed and keeps requests clearly separate from execution',async({page},info)=>{
  await page.goto('/platform')
  await page.getByRole('button',{name:'Data connections',exact:true}).click()
  await page.getByRole('button',{name:'Add connection'}).click()
  const form=page.getByRole('dialog',{name:'Add data connection'})
  await expect(form.getByRole('textbox',{name:'Public HTTPS feed URL'})).toHaveCount(0)
  await form.getByRole('textbox',{name:'Connection name',exact:true}).fill(`Synthetic daily feed ${info.project.name}`)
  await form.getByRole('combobox',{name:'Data source',exact:true}).selectOption('carfax')
  await form.getByRole('textbox',{name:'Provider or vendor name'}).fill('CARFAX')
  await form.getByRole('combobox',{name:'Connection method'}).selectOption('api')
  await form.getByRole('textbox',{name:'Public HTTPS feed URL'}).fill('https://feed.example.invalid/history')
  await form.getByRole('combobox',{name:'Pull schedule'}).selectOption('daily')
  await form.getByLabel('Local start time').fill('05:45')
  await form.getByRole('textbox',{name:'IANA timezone'}).fill('America/Detroit')
  await expect(form.getByRole('checkbox',{name:'Source enabled'})).not.toBeChecked()
  await form.getByRole('checkbox',{name:'Source enabled'}).check()
  await form.getByRole('textbox',{name:'Reason for this change'}).fill('Synthetic daily source setup')
  await form.getByRole('button',{name:'Save change'}).click()
  await expect(page.getByRole('heading',{name:`Synthetic daily feed ${info.project.name}`,exact:true})).toBeVisible()
  await expect(page.getByRole('definition').filter({hasText:'Daily 05:45'})).toBeVisible()
  await expect(page.getByText('Daily planner not activated',{exact:true})).toBeVisible()
  await expect(page.getByText('Executor not connected',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Request pull',exact:true}).click()
  await page.getByRole('dialog').getByRole('textbox',{name:'Reason for this change'}).fill('Synthetic read-only pull')
  await page.getByRole('dialog').getByRole('button',{name:'Save change'}).click()
  await expect(page.getByRole('button',{name:'Cancel request'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Request pull',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Cancel request'}).click()
  await page.getByRole('dialog').getByRole('textbox',{name:'Reason for this change'}).fill('Synthetic request cancellation')
  await page.getByRole('dialog').getByRole('button',{name:'Save change'}).click()
  await expect(page.getByRole('button',{name:'Configure'})).toBeEnabled()
})

test('creates an OEM-scoped source from its dealership and preserves the family for other providers',async({page},info)=>{
  await page.goto('/platform')
  await page.getByRole('button',{name:'Data connections',exact:true}).click()
  await page.getByRole('button',{name:'OEM coverage',exact:true}).click()
  const coverage=page.getByRole('region',{name:'OEM coverage',exact:true})
  await coverage.getByRole('combobox',{name:'OEM family'}).selectOption('toyota_lexus')
  const add=coverage.getByRole('button',{name:/Add Toyota \/ Lexus source for/}).first()
  const dealer=(await add.getAttribute('aria-label'))!.split(' source for ')[1]
  await add.click()
  const form=page.getByRole('dialog',{name:'Add data connection'})
  await expect(form.getByRole('combobox',{name:'Dealership',exact:true}).locator('option:checked')).toHaveText(dealer)
  await expect(form.getByRole('combobox',{name:'OEM connection'})).toHaveValue('toyota_lexus')
  await form.getByRole('combobox',{name:'Data source',exact:true}).selectOption('equipment')
  await expect(form.getByRole('combobox',{name:'OEM connection'})).toHaveValue('toyota_lexus')
  await expect(form.getByRole('checkbox',{name:'Source enabled'})).not.toBeChecked()
  const name=`Synthetic Toyota equipment ${info.project.name}`
  await form.getByRole('textbox',{name:'Connection name',exact:true}).fill(name)
  await form.getByRole('textbox',{name:'Provider or vendor name'}).fill('Authorized sample provider')
  await form.getByRole('textbox',{name:'Reason for this change'}).fill('Synthetic OEM configuration')
  await form.getByRole('button',{name:'Save change'}).click()
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Request pull',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'OEM coverage',exact:true}).click()
  await coverage.getByRole('combobox',{name:'OEM family'}).selectOption('toyota_lexus')
  const cell=coverage.getByRole('group',{name:`Toyota / Lexus at ${dealer}`})
  await expect(cell.getByRole('button',{name:`View ${name}`,exact:true})).toBeVisible()
  await cell.getByRole('button',{name:`View ${name}`,exact:true}).click()
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  const back=page.getByRole('button',{name:'Back to sources',exact:true})
  if(await back.isVisible()) await back.click()
  await page.getByRole('textbox',{name:'Find a connection'}).fill(name)
  await expect(page.getByRole('region',{name:'Source directory'}).getByRole('button',{name:/Inspect/})).toHaveCount(1)
  await page.getByRole('region',{name:'Source directory'}).getByRole('button',{name:/Inspect/}).click()
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})

test('keeps configuration dialogs keyboard contained and restores the launch action',async({page})=>{
  await page.goto('/platform')
  await page.getByRole('button',{name:'Data connections',exact:true}).click()
  const configure=page.getByRole('button',{name:'Configure'})
  await configure.click()
  const dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Save change'}).focus()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button',{name:'Close dialog'})).toBeFocused()
  await expect(page.locator('body')).toHaveCSS('overflow','hidden')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(configure).toBeFocused()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})

test('keeps keyboard focus in the responsive source workspace',async({page})=>{
  await page.goto('/platform')
  await page.getByRole('button',{name:'Data connections',exact:true}).click()
  const back=page.getByRole('button',{name:'Back to sources',exact:true})
  const heading=page.getByRole('article',{name:'Selected source configuration'}).getByRole('heading')
  await expect(heading).toBeVisible()
  if(!await back.isVisible()) return
  const name=await heading.innerText()
  await back.click()
  const row=page.getByRole('button',{name:new RegExp(`^Inspect ${name} at `)})
  await expect(row).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(heading).toBeFocused()
  await expect(row).toBeHidden()
  await back.click()
  await expect(row).toBeFocused()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})
